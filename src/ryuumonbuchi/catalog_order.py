_TOOL_INDEX: dict[str, int] = {name: i for i, name in enumerate(TOOL_ORDER)}


def order_specs(specs: list[ToolSpec]) -> list[ToolSpec]:
    """Sort specs to the pinned observable order; unknown names raise rather than drift."""
    return sorted(specs, key=lambda spec: _TOOL_INDEX[spec.name])
